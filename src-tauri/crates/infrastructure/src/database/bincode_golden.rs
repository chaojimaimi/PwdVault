/// 257-byte mixed pattern: full 0x00-0xFF cycle plus one extra 0xFF.
fn long_pattern() -> Vec<u8> {
    (0..257u32).map(|i| (i * 7 % 256) as u8).collect()
}

fn sample_encrypted_data_empty() -> EncryptedData {
    EncryptedData {
        nonce: vec![],
        ciphertext: vec![],
    }
}

fn sample_encrypted_data_populated() -> EncryptedData {
    EncryptedData {
        nonce: (0u8..12).collect(),
        ciphertext: long_pattern(),
    }
}


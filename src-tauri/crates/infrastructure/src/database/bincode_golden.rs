//! Golden byte fixtures pinning the on-disk serialization format.
//!
//! **Provenance**: every `*_HEX` constant below was produced by **bincode
//! 1.3.3** on `main @ b9185a2` (v1.2.4) with `bincode::serialize` — captured
//! BEFORE the v1.3.0 bincode 1 → 2 dependency swap, while 1.3.3 was still on
//! the tree. The samples cover the §0 matrix: empty/`None` boundaries,
//! `i64::MIN`/`u64::MAX`/`usize::MAX` extremes, multi-byte UTF-8, and long
//! `Vec`s (257-byte pattern).
//!
//! **These tests are the legacy-compatibility tripwire.** If upgrading
//! bincode 2.x (or the `bc_serialize`/`bc_deserialize` config) makes any of
//! them red, the legacy byte semantics have drifted: on-disk rows written by
//! older app versions would stop reading back. Any such change MUST be
//! evaluated for disk compatibility in the same commit — either the config
//! is restored to byte-parity, or a read-side migration is designed and
//! shipped deliberately.
//!
//! The single serialization seam is [`crate::crypto::bc_serialize`] /
//! [`crate::crypto::bc_deserialize`] (bincode 2 serde bridge with
//! `config::legacy()`); a future postcard migration only changes that seam —
//! these fixtures are what proves the replacement is byte-safe.


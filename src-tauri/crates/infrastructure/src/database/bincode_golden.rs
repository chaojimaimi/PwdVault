fn decode_hex(s: &str) -> Vec<u8> {
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).expect("fixture hex is well-formed"))
        .collect()
}

/// The golden assertion pair: (1) `bc_serialize` must reproduce the bincode
/// 1.3.3 bytes exactly; (2) the fixture must deserialize back to an equal
/// value. Debug-format comparison stands in for `PartialEq` (these domain
/// types deliberately do not derive it).
fn assert_golden<T>(hex_fixture: &str, value: &T)
where
    T: Serialize + DeserializeOwned + std::fmt::Debug,
{
    let bytes = decode_hex(hex_fixture);
    assert_eq!(
        bc_serialize(value).expect("bc_serialize is infallible for these shapes"),
        bytes,
        "serialized bytes diverge from the bincode 1.3.3 golden fixture — \
         legacy disk-format drift, see bincode_golden.rs module docs"
    );
    let decoded: T =
        bc_deserialize(&bytes).expect("golden fixture must deserialize via bc_deserialize");
    assert_eq!(
        format!("{:?}", decoded),
        format!("{:?}", value),
        "fixture did not round-trip to an equal value"
    );
}

